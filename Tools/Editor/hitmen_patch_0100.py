def wanted(step):
    return not STEPS or step in STEPS


def load(asset_path):
    return EAL.load_asset(asset_path) if EAL.does_asset_exist(asset_path) else None


def save(asset):
    if asset:
        EAL.save_loaded_asset(asset, only_if_is_dirty=False)


def each_character_cdo(fn, paths=CHARACTERS):
    for bp_path in paths:
        bp = load(bp_path)
        if not bp:
            log("WARN missing", bp_path)
            continue
        fn(unreal.get_default_object(bp.generated_class()))
        unreal.BlueprintEditorLibrary.compile_blueprint(bp)
        save(bp)


def import_synth_sounds():
    """Tools/Audio/Synth/*.wav (generated by Tools/Audio/hitmen_synth_sfx.py) into Audio/SFX/Synth."""
    source = os.path.join(PROJECT, "Tools", "Audio", "Synth")
    if not EAL.does_directory_exist(SYNTH_FOLDER):
        EAL.make_directory(SYNTH_FOLDER)
    tasks = []
    for name in sorted(os.listdir(source)) if os.path.isdir(source) else []:
        if not name.lower().endswith(".wav"):
            continue
        task = unreal.AssetImportTask()
        task.set_editor_property("filename", os.path.join(source, name))
        task.set_editor_property("destination_path", SYNTH_FOLDER)
        task.set_editor_property("destination_name", os.path.splitext(name)[0])
        task.set_editor_property("automated", True)
        task.set_editor_property("replace_existing", True)
        task.set_editor_property("save", True)
        tasks.append(task)
    if tasks:
        AT.import_asset_tasks(tasks)
    return len(tasks)


